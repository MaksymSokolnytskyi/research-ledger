"""``ledger feedback``: a bug report or idea with the diagnostics already attached.

Beta feedback is only useful if it says what happened on the tester's machine, and
testers do not collect diagnostics by hand. This builds the report for them:

* version, Python and OS;
* counts from the last audit (no note names, no note text);
* local hook statistics from ``.ledger/usage.jsonl`` (calls, how often a hook spoke,
  latency);
* the last hook errors, redacted.

Nothing leaves the machine by itself. The report is written to ``.ledger/`` and shown;
it becomes a GitHub issue only through a link the user opens, or ``--submit`` (which
uses the user's own ``gh`` login).
"""

from __future__ import annotations

import platform
import shutil
import subprocess
from datetime import datetime
from pathlib import Path
from typing import Literal
from urllib.parse import urlencode

from research_ledger import __version__
from research_ledger.config import CONFIG_NAME, Vault
from research_ledger.redact import redact
from research_ledger.usage import summary

REPO = "MaksymSokolnytskyi/research-ledger"
Kind = Literal["bug", "idea", "comment"]
LABELS = {"bug": "bug", "idea": "enhancement", "comment": "feedback"}
URL_LIMIT = 7000  # browsers and GitHub accept roughly this much in a prefilled URL


def diagnostics(vault: Vault) -> str:
    lines = [
        f"- research-ledger {__version__}, Python {platform.python_version()}, "
        f"{platform.system()} {platform.release()}",
        f"- ledger.toml: {'yes' if (vault.root / CONFIG_NAME).is_file() else 'no'}, "
        f"language {vault.config.language}, inject {vault.config.context.inject}, "
        f"capture {'on' if vault.config.capture.enabled else 'off'}",
    ]
    try:
        from research_ledger.audit import run_audit

        metrics = run_audit(vault).metrics
        keys = (
            "notes",
            "words",
            "dangling_links",
            "orphans",
            "numbers_unsourced",
            "lifecycle_missing",
            "records",
            "failures",
            "repeat_failure_rate",
        )
        lines.append("- audit: " + ", ".join(f"{k} {metrics[k]}" for k in keys))
    except Exception as exc:  # the report must work exactly when things are broken
        lines.append(f"- audit failed: {type(exc).__name__}: {redact(str(exc))[:200]}")
    stats = summary(vault)
    if stats:
        lines.append(
            "- hooks (local stats): "
            + "; ".join(
                f"{event} {s['calls']} calls, spoke {s['spoke']}, "
                f"median {s['median_ms']} ms, p95 {s['p95_ms']} ms, errors {s['errors']}"
                for event, s in stats.items()
            )
        )
    errors = vault.state_dir / "hook_errors.log"
    if errors.is_file():
        tail = errors.read_text(encoding="utf-8", errors="replace").splitlines()[-5:]
        lines.append("- recent hook errors:")
        lines += [f"  - `{redact(line)[:300]}`" for line in tail]
    return "\n".join(lines)


def build_report(vault: Vault, kind: Kind, message: str) -> tuple[str, str]:
    """``(title, body)`` of the issue."""
    first_line = message.strip().splitlines()[0] if message.strip() else kind
    title = f"[{kind}] {first_line[:80]}"
    body = (
        f"## What happened / what I would like\n\n{message.strip() or '(describe)'}\n\n"
        f"## Diagnostics (generated by `ledger feedback`)\n\n{diagnostics(vault)}\n"
    )
    return title, body


def issue_url(kind: Kind, title: str, body: str) -> str:
    params = {"title": title, "labels": LABELS[kind], "body": body}
    url = f"https://github.com/{REPO}/issues/new?{urlencode(params)}"
    if len(url) > URL_LIMIT:  # keep the link working; the full report is in the file
        params["body"] = (
            body[:2000] + "\n\n(truncated: paste the rest from the saved file)"
        )
        url = f"https://github.com/{REPO}/issues/new?{urlencode(params)}"
    return url


def save_report(vault: Vault, title: str, body: str) -> Path:
    vault.state_dir.mkdir(parents=True, exist_ok=True)
    path = vault.state_dir / f"feedback-{datetime.now():%Y%m%d-%H%M%S}.md"
    path.write_text(f"# {title}\n\n{body}", encoding="utf-8")
    return path


def submit(kind: Kind, title: str, body_file: Path) -> tuple[bool, str]:
    """Create the issue with the user's own ``gh`` login. Returns (ok, message)."""
    gh = shutil.which("gh")
    if gh is None:
        return False, "GitHub CLI (gh) not found; open the link instead."
    try:
        out = subprocess.run(
            [
                gh,
                "issue",
                "create",
                "--repo",
                REPO,
                "--title",
                title,
                "--body-file",
                str(body_file),
                "--label",
                LABELS[kind],
            ],
            capture_output=True,
            text=True,
            timeout=60,
            encoding="utf-8",
        )
        if out.returncode != 0 and "label" in out.stderr.lower():
            out = subprocess.run(  # labels may not exist yet in the repository
                [
                    gh,
                    "issue",
                    "create",
                    "--repo",
                    REPO,
                    "--title",
                    title,
                    "--body-file",
                    str(body_file),
                ],
                capture_output=True,
                text=True,
                timeout=60,
                encoding="utf-8",
            )
    except (OSError, subprocess.SubprocessError) as exc:
        return False, f"gh failed: {exc}"
    if out.returncode != 0:
        return False, (out.stderr or out.stdout).strip()[:300]
    return True, out.stdout.strip()


def main_feedback(vault: Vault, kind: Kind, message: str, do_submit: bool) -> int:
    title, body = build_report(vault, kind, message)
    path = save_report(vault, title, body)
    print(f"{title}\n\n{body}")
    print(f"saved: {path}")
    if do_submit:
        ok, msg = submit(kind, title, path)
        print(msg)
        return 0 if ok else 1
    print(
        f"\nopen to file it (nothing is sent until you submit on GitHub):\n"
        f"{issue_url(kind, title, body)}"
    )
    return 0
